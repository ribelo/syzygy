#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_model_magic_extraction() {
        let mut model = AppModel::default();
        model.users = vec!["test_user".to_string()];
        model.counter = 42;
        model.current_user = Some("alice".to_string());
        
        // Test the magic handler
        let result = MagicHandler::call(handle_add_user, &mut model);
        
        assert_eq!(result.events.len(), 1);
        assert_eq!(result.commands.len(), 1);
        
        if let AppEvent::UserAdded { name } = &result.events[0] {
            assert_eq!(name, "user_43");
        } else {
            panic!("Expected UserAdded event");
        }
    }
    
    #[test]
    fn test_resource_magic_extraction() {
        let mut resources = AppResources::default();
        
        // Test the magic handler with resources
        let result = MagicHandler::call(handle_system_startup, &mut resources);
        
        assert_eq!(result.commands.len(), 1);
        
        if let AppCommand::LogEvent { message } = &result.commands[0] {
            assert_eq!(message, "System started successfully");
        } else {
            panic!("Expected LogEvent command");
        }
    }
    
    #[test]
    fn test_field_extraction_types() {
        let model = AppModel::default();
        
        // Test direct extraction
        let users: Vec<String> = FromContainer::from_container(&model);
        assert_eq!(users.len(), 0);
        
        let counter: i32 = FromContainer::from_container(&model);
        assert_eq!(counter, 0);
        
        // Test newtype extraction
        let current_user: CurrentUser = FromContainer::from_container(&model);
        assert_eq!(*current_user, None);
        
        let active_user: ActiveUser = FromContainer::from_container(&model);
        assert_eq!(*active_user, None);
    }
    
    #[test]
    fn test_resource_extraction_types() {
        let resources = AppResources::default();
        
        // Test direct extraction
        let database: Database = FromContainer::from_container(&resources);
        assert_eq!(database.connection_string, "sqlite://app.db");
        
        let logger: Logger = FromContainer::from_container(&resources);
        assert_eq!(logger.level, "info");
        
        // Test newtype extraction
        let main_api: MainApi = FromContainer::from_container(&resources);
        assert_eq!(main_api.base_url, "https://api.example.com");
        
        let backup_api: BackupApi = FromContainer::from_container(&resources);
        assert_eq!(backup_api.base_url, "https://backup.example.com");
    }
}